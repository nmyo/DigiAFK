const assert = require('node:assert/strict');
const fs = require('node:fs');
const { patch } = require('./patch-offline-entries.cjs');
const bootPath = 'site/boot.js', appPath = 'site/bundle/app.c74e480997.js';
const boot = fs.readFileSync(bootPath, 'utf8'), app = fs.readFileSync(appPath, 'utf8');
assert.doesNotMatch(boot, /id="(?:guide-btn|save-btn)"/);
assert.doesNotMatch(app, /a\("#save-btn"\)\.onclick=S/);
assert.doesNotMatch(app, /class="ti-row"|a\("\.ti-how-btn",yt\)\.onclick|a\("\.ti-cl-btn",yt\)\.onclick/);
assert.match(app, /a\("\.ti-go",yt\)\.onclick=/);
assert.doesNotMatch(app, /id:"community"|class="op-community"|closest\?\.\("#guide-btn"\)/);
assert.doesNotMatch(app, /id:"account"|class="ti-account"/);
assert.doesNotMatch(boot, /data-screen="raid"/);
assert.doesNotMatch(app, /劇情回放|繼續冒險以發現更多劇情/);
assert.doesNotMatch(app, /id:"news",name:e\("Nouveautés"\)|B\(qe,"(?:guide|changelog)"|t\.Changelog\.badge\(\)/);
assert.match(app, /id:"advanced",name:e\("Avancé"\)/);
assert.doesNotMatch(boot, /data-grp="social"|data-screen="achievements"|id="screen-achievements"/);
assert.doesNotMatch(app, /data-ach|t\.Screens\.achievements|t\.Guide=function|t\.Changelog=function|data-screen="(?:trade|friends)"'\),/);
assert.doesNotMatch(boot, /data-screen="cinematics"|id="screen-cinematics"/);
assert.doesNotMatch(boot, /class="side-disc"/);
assert.doesNotMatch(app, /t\.Screens\.cinematics=|replayCinematic\(button\.dataset\.cine\)/);
assert.match(app, /function ln\(o,z,ke\)/);
patch();
assert.equal(fs.readFileSync(bootPath, 'utf8'), boot);
assert.equal(fs.readFileSync(appPath, 'utf8'), app);
console.log('Removed guide and title guide/changelog entries; patch is idempotent.');
